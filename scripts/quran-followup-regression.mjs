import assert from 'node:assert/strict';
import {QURAN_FOLLOWUP_WEEKS,resolveQuranWeek,QURAN_TRACKING_STUDENT_IDS,QURAN_FOLLOWUP_ROSTER} from '../server/quran-followup-curriculum.js';
import {CLASS_STUDENTS,getStudent} from '../server/class-roster.js';
import {readFileSync} from 'node:fs';

const api=readFileSync('server/quran-followup-api.js','utf8');
const app=readFileSync('src/main.tsx','utf8');
const css=readFileSync('src/ui.css','utf8');
const automation=readFileSync('api/learning-automation.js','utf8');
const homeworkBridge=readFileSync('public/student-automation-bridge.js','utf8');

assert.equal(QURAN_TRACKING_STUDENT_IDS.length,30,'Quran follow-up must use the 30 supplied real student IDs');
assert.equal(new Set(QURAN_TRACKING_STUDENT_IDS).size,30,'student IDs must be unique');
assert.equal(CLASS_STUDENTS.length,29,'do not mutate the existing class roster');
assert.equal(QURAN_FOLLOWUP_ROSTER.length,30);
assert(QURAN_TRACKING_STUDENT_IDS.every(id=>getStudent(id)),'each tracked student ID must resolve in the student profile API');
assert.equal(QURAN_FOLLOWUP_ROSTER[28].name,'راكان عبدالله الأحمدي');
assert.equal(QURAN_FOLLOWUP_ROSTER[29].name,'معن أيمن الأحمدي');
assert(QURAN_TRACKING_STUDENT_IDS.includes('s2-4-30')&&QURAN_TRACKING_STUDENT_IDS.includes('s2-4-31'));
assert(!QURAN_TRACKING_STUDENT_IDS.includes('s2-4-14'),'do not include the student absent from the supplied Quran roster');
assert.equal(QURAN_FOLLOWUP_WEEKS[1].surah,'الليل');
assert.equal(QURAN_FOLLOWUP_WEEKS[2].surah,'الشمس');
assert.equal(QURAN_FOLLOWUP_WEEKS[10].surah,'الأعلى');
assert.equal(QURAN_FOLLOWUP_WEEKS[11].surah,'الطارق');
assert.equal(QURAN_FOLLOWUP_WEEKS[12].surah,'البروج');
assert.equal(QURAN_FOLLOWUP_WEEKS[16].description,'مراجعة عامة');
assert.equal(QURAN_FOLLOWUP_WEEKS[17].kind,'exam');
assert.equal(QURAN_FOLLOWUP_WEEKS[17].surah,'');
assert.equal(resolveQuranWeek(13),null,'the unnumbered autumn break has no assessment week');
assert.equal(resolveQuranWeek(14)?.week,13,'curriculum week 13 follows the autumn break');
assert(api.includes("process.env.VERCEL_ENV!=='preview'")&&api.includes("process.env.VERCEL_ENV==='production'"),'Quran tracking endpoints must reject Production');
assert(api.includes("action==='quran-teacher-login'")&&api.includes("action==='quran-teacher-roster'")&&api.includes('teacherAuthorized(req)'));
assert(api.includes('verifyGuardian(studentId')&&api.includes('inviteToken'),'guardian reads must require the student-specific invite');
assert(api.includes("new Set(['MASTERED','NEEDS_REPEAT','NOT_MASTERED'])"),'only the three requested statuses are allowed');
assert(api.includes('entries.length!==30')&&api.includes('batch.commit()'),'save must validate and batch all 30 students');
assert(app.includes('function TeacherQuranFollowup')&&app.includes('أتقن الطلاب الكل')&&app.includes('حفظ التقييم'));
assert(app.includes('function QuranFollowupStudent')&&app.includes('عرض السجل')&&app.includes('متابعة حفظ القرآن الكريم'));
assert(css.includes('.quranTeacherPage')&&css.includes('.quranParentCard'));
assert(automation.includes("if(subject==='arabic'){")&&automation.includes('تُحل تمارين المهارات والظواهر اللغوية داخل الفصل في كتاب لغتي'));
assert(automation.includes('كتاب فن الخط')&&automation.includes('اكتب بخط جميل'));
for(const [lesson,page] of [['صلة الرحم',34],['عذرًا يا جدي',45],['الصديقان',69],['الجار الصغير',80],['مدينتان مقدستان',103],['علم بلادي',112],['رحلة حبة قمح',135],['من أنا؟',145]])assert(automation.includes(`'${lesson}':${page}`),`copywork mapping: ${lesson}`);
assert(automation.includes("taskType:subject==='quran'?quranTaskType(daySpecific,item):subject==='spelling'?'spelling_practice':subject==='arabic'?'copywriting'"));
assert(homeworkBridge.includes("task.taskType==='copywriting'")&&homeworkBridge.includes('تمرين الخط والنسخ'));
assert(homeworkBridge.includes('تم الإنجاز ✓'));
console.log('Quran follow-up curriculum, roster, privacy, UI and automation regression checks passed.');
