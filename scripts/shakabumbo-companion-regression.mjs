import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
assert(existsSync('src/app/assets/shak-original-full.webp'));
const rig=read('src/app/shakabumbo/ShakabumboRig.tsx'),css=read('src/app/app.src.css');
assert(rig.includes('shak-original-full.webp')&&!rig.includes('<svg')&&!rig.includes('shak-head-real'),'use one full original character');
assert(!css.includes('shakHeadTalk')&&!css.includes('shakLegFront'),'remove the disconnected head and distorted body animations');
assert(css.includes('.shakCompanionShelf{display:flex')&&!/\.shakCompanionShelf\{[^}]*position:fixed/.test(css),'reserve page space');
assert(css.includes('prefers-reduced-motion:reduce')&&css.includes('shakQuiet'),'quiet and reduced motion');
const chat=read('src/app/shakabumbo/ShakabumboChat.tsx'),voice=read('src/app/shakabumbo/voice-session.ts');
assert(chat.includes('<dialog')&&chat.includes('showModal()'),'keyboard accessible voice dialog');
assert(chat.includes('if(recognitionCtor()')&&chat.includes('session.start()'),'start voice directly on open');
assert(chat.includes('{typing&&<form'),'typing must be secondary');
assert(voice.includes('r.abort()')&&voice.includes('generation'),'prevent feedback and stale callbacks');
assert(!/fetch\(|WebSocket|OPENAI_API_KEY/.test(chat+voice),'no paid voice transport');
assert(!read('src/app/shakabumbo/speak.ts').includes('stripTashkeel'),'preserve educational vowels');
assert(read('src/app/learning-pilot.tsx').includes('assessment:step===2'),'assessment context must restrict help');
console.log('Original artwork, free voice lifecycle and Quran regression checks passed.');
