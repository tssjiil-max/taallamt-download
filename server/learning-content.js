export function riyadhDateString(date=new Date()){
  const parts=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Riyadh',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(date);
  const value=Object.fromEntries(parts.map(part=>[part.type,part.value]));
  return `${value.year}-${value.month}-${value.day}`;
}
export function riyadhWeekday(date=new Date()){
  const short=new Intl.DateTimeFormat('en-US',{timeZone:'Asia/Riyadh',weekday:'short'}).format(date);
  return ({Sun:0,Mon:1,Tue:2,Wed:3,Thu:4,Fri:5,Sat:6})[short];
}
export function weekNumberForDate(date=new Date()){
  const current=Date.parse(`${riyadhDateString(date)}T00:00:00Z`),start=Date.parse(`${TERM_START}T00:00:00Z`);
  return Math.max(1,Math.min(TERM_WEEKS,Math.floor((current-start)/86400000/7)+1));
}
